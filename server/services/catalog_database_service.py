SCAN_THREADS = 4
READY_STREAM_BITRATE = "128k"

def is_hidden_track(metadata: Optional[Dict]) -> bool:
    return (metadata or {}).get("visibility", "public") in ("unlisted", "private")


def station_recency(metadata: Dict) -> str:
    return metadata.get("catalog_added_at") or metadata.get("created_at", "")


class CatalogDatabaseService(SingletonService):
    def __init__(self):
        if getattr(self, '_initialized', False):
            return
        self.metadata_dir = settings.METADATA_DIR
        self.audio_dir = settings.AUDIO_DIR
        self.artwork_dir = settings.ARTWORK_DIR
        self.tracks = {}
        self.hidden_ids = set()
        self.human_ids = set()
        self.track_ids = []
        self._catalog_initialized = False
        self._artwork_cache = {}
        self._initialized = True
        self.vector_db_service = None
        self.broadcast_callback = None
        self._catalog_version = 0
        self._phrase_cache = {}
        self._scan_executor = ThreadPoolExecutor(max_workers=SCAN_THREADS, thread_name_prefix="catalog")
        self._initialize_database()

    def _get_connection(self):
        return get_pooled_connection(settings.CATALOG_DATABASE_URL)

    def _initialize_database(self):
        conn = self._get_connection()
        c = conn.cursor()

        c.execute('''CREATE TABLE IF NOT EXISTS tracks
                     (
                         rowid INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE,
                         track_id TEXT UNIQUE NOT NULL,
                         metadata_json TEXT NOT NULL,
                         created_at TEXT,
                         title TEXT,
                         primary_artist TEXT,
                         primary_genre TEXT,
                         duration INTEGER,
                         instrumental INTEGER,
                         vocal_gender TEXT,
                         has_mp3 INTEGER DEFAULT 0,
                         has_wav INTEGER DEFAULT 0,
                         has_artwork INTEGER DEFAULT 0,
                         is_ai_generated INTEGER DEFAULT 1,
                         uploaded_by_user_id INTEGER DEFAULT NULL
                     )''')

        c.execute('CREATE UNIQUE INDEX IF NOT EXISTS idx_track_id ON tracks(track_id)')
        c.execute('CREATE INDEX IF NOT EXISTS idx_created_at ON tracks(created_at DESC)')
        c.execute('CREATE INDEX IF NOT EXISTS idx_primary_genre ON tracks(primary_genre)')
        c.execute('CREATE INDEX IF NOT EXISTS idx_primary_artist ON tracks(primary_artist)')
        c.execute('CREATE INDEX IF NOT EXISTS idx_uploaded_by_user_id ON tracks(uploaded_by_user_id)')

        conn.commit()
        conn.close()

        log_service.catalog("✓ Catalog database initialized (PostgreSQL)")

    async def initialize(self):
        if self._catalog_initialized:
            return
        tracks, track_ids, artwork_cache = await self._scan_catalog()
        self._swap_catalog(tracks, track_ids, artwork_cache)
        self._catalog_initialized = True

    def _swap_catalog(self, tracks: Dict[str, Dict], track_ids: List[str], artwork_cache: Dict[str, bool]):
        self.tracks = tracks
        self.track_ids = track_ids
        self._artwork_cache = artwork_cache
        self.hidden_ids = {tid for tid, meta in tracks.items() if is_hidden_track(meta)}
        self.human_ids = {tid for tid, meta in tracks.items() if meta.get("is_ai_generated") is False}
        self._bump_version()

    def _bump_version(self):
        self._catalog_version += 1
        self._phrase_cache = {}

    def add_track_to_memory(self, track_id: str, metadata: Dict, has_artwork: Optional[bool] = None):
        self.tracks[track_id] = metadata
        if is_hidden_track(metadata):
            self.hidden_ids.add(track_id)
        else:
            self.hidden_ids.discard(track_id)
        if metadata.get("is_ai_generated") is False:
            self.human_ids.add(track_id)
        else:
            self.human_ids.discard(track_id)
        if track_id not in self.track_ids:
            self.track_ids.insert(0, track_id)
        if has_artwork is not None:
            self._artwork_cache[track_id] = has_artwork
        self._bump_version()

    def remove_track_from_memory(self, track_id: str):
        self.tracks.pop(track_id, None)
        self.hidden_ids.discard(track_id)
        self.human_ids.discard(track_id)
        if track_id in self.track_ids:
            self.track_ids.remove(track_id)
        self._artwork_cache.pop(track_id, None)
        self._bump_version()

    async def _in_scan_thread(self, func, *args):
        return await asyncio.get_running_loop().run_in_executor(self._scan_executor, func, *args)

    async def _scan_catalog(self):
        tracks: Dict[str, Dict] = {}
        track_ids: List[str] = []
        artwork_cache: Dict[str, bool] = {}

        log_service.catalog("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━")
        log_service.catalog("Loading Catalog from JSON → PostgreSQL Database")

        if not self.metadata_dir.exists():
            log_service.warning(f"Metadata directory not found: {self.metadata_dir}")
            return tracks, track_ids, artwork_cache

        stored = await self._in_scan_thread(self._stored_rows)
        file_ids = await self._in_scan_thread(lambda: [f.stem for f in self.metadata_dir.glob("*.json")])
        results = await asyncio.gather(*[self._in_scan_thread(self._scan_file, tid, stored.get(tid))
                                         for tid in file_ids])

        counts = Counter()
        on_file = set(file_ids)
        gone = [tid for tid in stored if tid not in on_file]
        for res in results:
            if res is None:
                continue
            tid, meta, state, art_exists = res
            if meta is None:
                if tid in stored:
                    gone.append(tid)
                continue
            tracks[tid] = meta
            artwork_cache[tid] = art_exists
            track_ids.append(tid)
            counts[state] += 1
        if gone:
            log_service.catalog(f"Removing {len(gone)} tracks without metadata or master WAV...")
            await self._in_scan_thread(self._bulk_delete_tracks, gone)

        track_ids.sort(key=lambda tid: station_recency(tracks[tid]), reverse=True)

        log_service.catalog(
            f"📊 Sync complete: {len(tracks)} total | +{counts['new']} new | ~{counts['updated']} updated | "
            f"={counts['same']} unchanged | -{len(gone)} removed")
        log_service.catalog("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━")
        return tracks, track_ids, artwork_cache

    def _scan_file(self, track_id: str, stored: Optional[Tuple]) -> Optional[Tuple]:
        from services.suno_metadata_service import MusicMetadata
        try:
            metadata = MusicMetadata().read_metadata(track_id)
            if not metadata:
                return None
            flags = self.compute_track_flags(track_id)
            if not flags[1]:
                return track_id, None, "no_master", False
            metadata['id'] = track_id
            if stored == (self._fingerprint(metadata), *flags):
                return track_id, metadata, "same", flags[2]
            is_new = self._upsert_track_to_db(track_id, metadata, *flags)
            return track_id, metadata, "new" if is_new else "updated", flags[2]
        except Exception as e:
            log_service.error(f"Error processing {track_id}.json: {e}")
            return None

    @staticmethod
    def _fingerprint(metadata: Dict) -> str:
        return hashlib.md5(json.dumps(metadata).encode("utf-8")).hexdigest()

    def _stored_rows(self) -> Dict[str, Tuple]:
        conn = self._get_connection()
        try:
            c = conn.cursor()
            c.execute("SELECT track_id, md5(metadata_json), has_mp3, has_wav, has_artwork FROM tracks")
            return {tid: (digest, bool(mp3), bool(wav), bool(art)) for tid, digest, mp3, wav, art in c.fetchall()}
        finally:
            conn.close()

    def _bulk_delete_tracks(self, track_ids: List[str]):
        conn = self._get_connection()
        c = conn.cursor()
        c.executemany("DELETE FROM tracks WHERE track_id = %s", [(tid,) for tid in track_ids])
        conn.commit()
        conn.close()

    def _delete_track_from_db(self, track_id: str):
        conn = self._get_connection()
        c = conn.cursor()
        c.execute("DELETE FROM tracks WHERE track_id = %s", (track_id,))
        conn.commit()
        conn.close()

    def _upsert_track_to_db(self, track_id: str, metadata: Dict, has_mp3: bool, has_wav: bool,
                            has_artwork: bool) -> bool:
        params = metadata.get("generation_params", {}) or {}
        derived = metadata.get("derived_tags", {}) or {}
        info = metadata.get("track_info", {}) or {}

        title = (params.get("title") or "").strip()
        artist = (params.get("artist_name") or "").strip()
        genre = (derived.get("primary_genre") or "").strip()
        vocal_gender = (params.get("vocal_gender") or "").strip()

        is_ai_generated = 1 if metadata.get("is_ai_generated", True) else 0
        uploaded_by_user_id = metadata.get("uploaded_by_user_id")

        conn = self._get_connection()
        c = conn.cursor()
        c.execute('''INSERT INTO tracks (metadata_json, created_at, title, primary_artist, primary_genre,
                                         duration, instrumental, vocal_gender, has_mp3, has_wav, has_artwork,
                                         is_ai_generated, uploaded_by_user_id, track_id)
                     VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                     ON CONFLICT (track_id) DO UPDATE
                     SET metadata_json = EXCLUDED.metadata_json,
                         created_at = EXCLUDED.created_at,
                         title = EXCLUDED.title,
                         primary_artist = EXCLUDED.primary_artist,
                         primary_genre = EXCLUDED.primary_genre,
                         duration = EXCLUDED.duration,
                         instrumental = EXCLUDED.instrumental,
                         vocal_gender = EXCLUDED.vocal_gender,
                         has_mp3 = EXCLUDED.has_mp3,
                         has_wav = EXCLUDED.has_wav,
                         has_artwork = EXCLUDED.has_artwork,
                         is_ai_generated = EXCLUDED.is_ai_generated,
                         uploaded_by_user_id = EXCLUDED.uploaded_by_user_id
                     RETURNING (xmax = 0)''',
                  (json.dumps(metadata), metadata.get("created_at", ""), title,
                   artist, genre, info.get("duration", 0),
                   1 if params.get("instrumental") else 0, vocal_gender,
                   int(has_mp3), int(has_wav), int(has_artwork),
                   is_ai_generated, uploaded_by_user_id, track_id))
        inserted = c.fetchone()[0]

        conn.commit()
        conn.close()
        return inserted

    def compute_track_flags(self, track_id: str) -> Tuple[bool, bool, bool]:
        has_mp3 = any((self.audio_dir / f"{track_id}{ext}").exists() for ext in CATALOG_AUDIO_EXTENSIONS)
        has_wav = (settings.ENHANCED_WAV_DIR / f"{track_id}.wav").exists()
        has_artwork = (self.artwork_dir / f"{track_id}.jpeg").exists()
        return has_mp3, has_wav, has_artwork

    def get_track_db_state(self, track_id: str) -> Optional[Dict[str, Any]]:
        conn = self._get_connection()
        try:
            c = conn.cursor()
            c.execute("SELECT rowid, has_mp3, has_wav, has_artwork FROM tracks WHERE track_id = %s", (track_id,))
            row = c.fetchone()
        finally:
            conn.close()
        if not row:
            return None
        return {"rowid": row[0], "has_mp3": bool(row[1]), "has_wav": bool(row[2]), "has_artwork": bool(row[3])}

    def update_track_flags(self, track_id: str, has_mp3: bool, has_wav: bool, has_artwork: bool) -> bool:
        conn = self._get_connection()
        try:
            c = conn.cursor()
            c.execute("UPDATE tracks SET has_mp3 = %s, has_wav = %s, has_artwork = %s WHERE track_id = %s",
                      (int(has_mp3), int(has_wav), int(has_artwork), track_id))
            updated = c.rowcount > 0
            conn.commit()
        finally:
            conn.close()
        if track_id in self.tracks:
            self._artwork_cache[track_id] = has_artwork
        return updated

    def refresh_track_flags(self, track_id: str) -> Tuple[bool, bool, bool]:
        flags = self.compute_track_flags(track_id)
        self.update_track_flags(track_id, *flags)
        return flags

    def write_track_metadata(self, track_id: str, metadata: Dict) -> Tuple[bool, bool, bool]:
        metadata_path = self.metadata_dir / f"{track_id}.json"
        temp_path = metadata_path.with_name(f"{track_id}.json.tmp")
        temp_path.write_text(json.dumps(metadata, indent=2, ensure_ascii=False), encoding="utf-8")
        os.replace(temp_path, metadata_path)
        return self._store_row(track_id, metadata)

    def _store_row(self, track_id: str, metadata: Dict) -> Tuple[bool, bool, bool]:
        flags = self.compute_track_flags(track_id)
        self._upsert_track_to_db(track_id, metadata, *flags)
        return flags

    def ready_files(self, track_id: str) -> List[Path]:
        return [
            settings.ENHANCED_WAV_DIR / f"{track_id}.wav",
            settings.AUDIOFEATURES_DIR / f"{track_id}.json",
            settings.LYRIC_TIMESTAMPS_DIR / f"{track_id}.json",
            self.artwork_dir / f"{track_id}.jpeg",
            webm_path(track_id, READY_STREAM_BITRATE),
        ]

    def is_ready(self, track_id: str) -> bool:
        return (self.metadata_dir / f"{track_id}.json").exists() and all(p.exists() for p in self.ready_files(track_id))

    async def add_finished_track(self, track_id: str, metadata: Optional[Dict] = None) -> bool:
        from services.suno_metadata_service import MusicMetadata
        if metadata is None:
            metadata = await self._in_scan_thread(MusicMetadata().read_metadata, track_id)
        if not metadata:
            log_service.warning(f"[Catalog] {track_id[:8]}: no metadata to add")
            return False
        metadata['id'] = track_id
        is_new = track_id not in self.tracks
        await self._index(track_id, metadata, await self._in_scan_thread(self._store_row, track_id, metadata))
        log_service.catalog(f"[Catalog] {'Added' if is_new else 'Updated'} {log_service.track_label(metadata)} "
                            f"({len(self.tracks)} tracks)")
        if is_new and self.broadcast_callback:
            await self.broadcast_callback("track", "added", {"track_id": track_id, "total_tracks": len(self.tracks)})
        return True

    async def update_track(self, track_id: str, metadata: Dict) -> Tuple[bool, bool, bool]:
        flags = await self._in_scan_thread(self.write_track_metadata, track_id, metadata)
        if track_id in self.tracks:
            await self._index(track_id, metadata, flags)
        return flags

    async def _index(self, track_id: str, metadata: Dict, flags: Tuple[bool, bool, bool]):
        self.add_track_to_memory(track_id, metadata, has_artwork=flags[2])
        if self.vector_db_service:
            try:
                await self._in_scan_thread(self.vector_db_service.add_rows, [track_id])
            except Exception as e:
                log_service.warning(f"[Catalog] {track_id[:8]}: search index update failed, the next rebuild "
                                    f"picks it up: {e}")

    def get_track(self, track_id: str) -> Optional[Dict]:
        return self.tracks.get(track_id)

    def get_all_tracks(self, skip: int = 0, limit: int = 100, sort_by: str = "created_at", order: str = "desc",
                       genre: Optional[str] = None, banned_ids: Optional[set] = None) -> tuple:
        ids = self.track_ids

        if genre:
            ids = [tid for tid in ids if
                   (self.tracks[tid].get("derived_tags", {}).get("primary_genre") or "").lower() == genre.lower()]

        if banned_ids or self.hidden_ids:
            excluded = (banned_ids or set()) | self.hidden_ids
            ids = [tid for tid in ids if tid not in excluded]

        filtered_total = len(ids)

        reverse = (order == "desc")
        if sort_by == "title":
            ids = sorted(ids, key=lambda tid: (self.tracks[tid].get("generation_params", {}).get("title") or "").lower(),
                         reverse=reverse)
        elif sort_by == "artist_name":
            ids = sorted(ids,
                         key=lambda tid: (self.tracks[tid].get("generation_params", {}).get("artist_name") or "").lower(),
                         reverse=reverse)
        elif sort_by == "genre":
            ids = sorted(ids,
                         key=lambda tid: (self.tracks[tid].get("derived_tags", {}).get("primary_genre") or "zzz").lower(),
                         reverse=reverse)
        elif sort_by != "created_at":
            ids = sorted(ids, key=lambda tid: station_recency(self.tracks[tid]), reverse=reverse)

        return [self.tracks[tid] for tid in ids[skip:skip + limit]], filtered_total

    def has_artwork(self, track_id: str) -> bool:
        if track_id in self._artwork_cache:
            return self._artwork_cache[track_id]
        exists = (self.artwork_dir / f"{track_id}.jpeg").exists()
        if track_id in self.tracks:
            self._artwork_cache[track_id] = exists
        return exists

    def update_track_artwork_status(self, track_id: str, has_artwork: bool) -> bool:
        conn = self._get_connection()
        c = conn.cursor()

        try:
            c.execute('''UPDATE tracks SET has_artwork = %s WHERE track_id = %s''',
                      (int(has_artwork), track_id))
            conn.commit()

            self._artwork_cache[track_id] = has_artwork

            log_service.info(f"[Catalog] Updated artwork status for {track_id}: {has_artwork}")
            return True
        except Exception as e:
            log_service.error(f"[Catalog] Failed to update artwork status: {e}")
            return False
        finally:
            conn.close()

    def set_vector_services(self, vector_db_service=None, broadcast_callback=None):
        self.vector_db_service = vector_db_service
        self.broadcast_callback = broadcast_callback

    def _finished_outside_catalog(self) -> List[str]:
        masters = {p.stem for p in settings.ENHANCED_WAV_DIR.glob("*.wav")}
        return [tid for tid in masters - set(self.tracks) if self.is_ready(tid)]

    async def watch_for_finished_tracks(self, interval_s: float):
        while True:
            await asyncio.sleep(interval_s)
            try:
                for track_id in await self._in_scan_thread(self._finished_outside_catalog):
                    if track_id not in self.tracks:
                        await self.add_finished_track(track_id)
            except Exception as e:
                log_service.throttled("catalog_watch", f"[Catalog] Watch for finished tracks failed: {e}")

    def get_all_genres(self) -> List[Dict]:
        cached = getattr(self, "_genres_cache", None)
        if cached is not None and cached[0] == self._catalog_version:
            return cached[1]
        version = self._catalog_version
        genres = self._count_genres()
        self._genres_cache = (version, genres)
        return genres

    def _count_genres(self) -> List[Dict]:
        counts = Counter()
        sub_genres = {}
        for t in self.tracks.values():
            d = t.get("derived_tags", {})
            pg = d.get("primary_genre")
            if pg:
                counts[pg] += 1
                if pg not in sub_genres:
                    sub_genres[pg] = set()
                sub_genres[pg].update(d.get("secondary_genres", []))

        return sorted([{"genre": g, "count": c, "sub_genres": sorted(list(sub_genres[g]))} for g, c in counts.items()],
                      key=lambda x: x["count"], reverse=True)

    def get_audio_path(self, track_id: str) -> Optional[Path]:
        return self.audio_dir / f"{track_id}.mp3" if track_id in self.tracks else None

    def get_artwork_path(self, track_id: str) -> Optional[Path]:
        return self.artwork_dir / f"{track_id}.jpeg" if self.has_artwork(track_id) else None

    def get_repeated_titles(self, min_occurrences: int = 2) -> List[str]:
        counts = Counter(
            (self.tracks[tid].get("generation_params", {}).get("title") or "").strip().lower()
            for tid in self.tracks if self.tracks[tid].get("generation_params", {}).get("title")
        )
        return [t for t, c in counts.most_common() if c >= min_occurrences]

    def get_repeated_artists(self) -> List[str]:
        counts = Counter(
            (self.tracks[tid].get("generation_params", {}).get("artist_name") or "").strip().lower()
            for tid in self.tracks if self.tracks[tid].get("generation_params", {}).get("artist_name")
        )
        if not counts:
            return []
        threshold = np.percentile(list(counts.values()), 85)
        return [a for a, c in counts.most_common() if c > threshold and c > 1]

    def get_repeated_phrases(self, min_occurrences: int = 2, top_n: int = 20) -> List[str]:
        cache_key = (self._catalog_version, len(self.tracks), min_occurrences, top_n)
        cached = self._phrase_cache.get(cache_key)
        if cached is not None:
            return list(cached)
        phrases = self._compute_repeated_phrases(min_occurrences, top_n)
        self._phrase_cache[cache_key] = phrases
        return list(phrases)

    def _compute_repeated_phrases(self, min_occurrences: int, top_n: int) -> List[str]:
        phrase_counts = Counter()
        for track in list(self.tracks.values()):
            prompt = track.get("generation_params", {}).get("prompt", "")
            if not prompt:
                continue
            words = re.sub(r'\[.*?]|\(.*?\)', '', prompt).lower().split()
            for n in range(4, 7):
                for i in range(len(words) - n + 1):
                    p = ' '.join(words[i:i + n])
                    if len(p) > 15:
                        phrase_counts[p] += 1
        return [p for p, c in phrase_counts.most_common(top_n) if c >= min_occurrences]

    def get_cycled_phrases(self, cycle_index: int = 0, phrases_per_cycle: int = 5, top_n: int = 20) -> List[str]:
        phrases = self.get_repeated_phrases(min_occurrences=2, top_n=top_n)
        if not phrases:
            return []
        idx = (cycle_index * phrases_per_cycle) % len(phrases)
        return (phrases + phrases)[idx: idx + phrases_per_cycle]

    async def get_tracks_by_artist(self, artist_name: str) -> Dict[str, Any]:
        artist_lower = (artist_name or "").strip().lower()

        matching_tracks = []
        for tid in self.tracks:
            track = self.tracks[tid]
            track_artist = (track.get("generation_params", {}).get("artist_name") or "").strip().lower()
            inspired_artist = (track.get("derived_tags", {}).get("inspired_artist") or "").strip().lower()

            if track_artist == artist_lower or inspired_artist == artist_lower:
                matching_tracks.append(track)

        if not matching_tracks:
            return {
                "artist": artist_name,
                "track_count": 0,
                "message": f"No existing tracks found for {artist_name}. This is a NEW artist for your catalog!"
            }

        unique_tracks = {}
        seen_titles = set()

        for track in matching_tracks:
            title = (track.get("generation_params", {}).get("title") or "Untitled").strip()
            title_lower = title.lower()

            if title_lower in seen_titles:
                continue

            theme = track.get("derived_tags", {}).get("lyrical_interpretation", "")

            if title and theme:
                unique_tracks[title] = theme
                seen_titles.add(title_lower)

        existing_tracks = [
            {"title": title, "theme": theme}
            for title, theme in list(unique_tracks.items())[:15]
        ]

        result = {
            "artist": artist_name,
            "track_count": len(matching_tracks),
            "unique_track_count": len(unique_tracks),
            "existing_tracks": existing_tracks,
            "advice": f"You have {len(unique_tracks)} unique tracks for {artist_name}. Avoid repeating these titles and themes - create something FRESH with different subject matter."
        }

        try:
            log_service.catalog(f"[Catalog Tool] Returning data for '{artist_name}':")
            log_service.catalog(f"  - {len(matching_tracks)} total tracks ({len(unique_tracks)} unique)")
        except Exception as e:
            log_service.warning(f"[Catalog Tool] Log error: {e}")

        return result

    def get_stats(self, genre: Optional[str] = None) -> Dict:
        total, duration, inst, vocal = 0, 0, 0, 0
        for tid, t in self.tracks.items():
            if genre:
                track_genre = (t.get("derived_tags", {}).get("primary_genre") or "").lower()
                if track_genre != genre.lower():
                    continue
            total += 1
            duration += t.get("track_info", {}).get("duration", 0)
            if t.get("generation_params", {}).get("instrumental"):
                inst += 1
            else:
                vocal += 1
        return {
            "total_tracks": total, "total_duration_ms": duration,
            "total_duration_formatted": self._format_duration(duration),
            "instrumental_count": inst, "vocal_count": vocal
        }

    def _format_duration(self, ms: int) -> str:
        m, s = divmod(ms // 1000, 60)
        h, m = divmod(m, 60)
        return f"{h}h {m}m" if h else f"{m}m {s}s"